SPEAKER_KO = {A: "상담사", C: "고객"}


def q(v) -> str:
    return "NULL" if v is None else "'" + str(v).replace("'", "''") + "'"


def build_sql() -> str:
    calls = PRE_CALLS + CALLS
    customers = {}
    for _, _, _, cid, name, gender, age, _, _ in calls:
        customers.setdefault(cid, (name, gender, age))
    out = [
        "-- =====================================================================",
        "-- 11. 등급별 시연 STT 원문 16건 + 누적 제보용 사전 통화 6건",
        "--   scripts/demo_scripts.py 로 생성한 파일입니다. 원문을 고치려면 그 파일을 고친 뒤 다시 실행하세요.",
        "--   - 실제 고객 정보·상담 원문이 아닌 가상 상담입니다.",
        "--   - 통화는 '진행' 상태로 들어가며, 상담현황에서 상담이력을 등록하면 에이전트가 분석합니다.",
        "--   - 사전 통화(DEMO-P1-x-PRE*)는 해당 대본보다 먼저, 60분 안에 등록해야 같은 장애로 묶입니다.",
        "--   여러 번 실행해도 안전합니다. 10_impact_improvement.sql 이후에 실행하세요.",
        "-- =====================================================================",
        "",
        "-- ---------- 시연 고객 ----------",
        "INSERT INTO customer (customer_id, customer_name, gender, age) VALUES",
        ",\n".join(f" ({q(cid)}, {q(n)}, {q(g)}, {a})" for cid, (n, g, a) in customers.items()),
        "ON CONFLICT (customer_id) DO NOTHING;",
        "",
        "-- ---------- STT 통화 (사전 통화가 먼저 보이도록 시작 시각을 앞에 둠) ----------",
        "INSERT INTO stt_call (call_id, customer_id, customer_name, agent_name, inbound_channel, started_at, duration_sec) VALUES",
    ]
    rows = []
    for i, (call_id, _, _, cid, name, _, _, agent, lines) in enumerate(calls):
        minutes = (len(calls) - i) * 2
        rows.append(f" ({q(call_id)}, {q(cid)}, {q(name)}, {q('상담사 ' + agent)}, '콜센터', "
                    f"now() - interval '{minutes} minutes', {len(lines) * 12})")
    out += [",\n".join(rows), "ON CONFLICT (call_id) DO NOTHING;", "", "-- ---------- STT 원문 ----------",
            "INSERT INTO stt_utterance (call_id, seq, speaker, offset_sec, text) VALUES"]
    rows = []
    for call_id, label, title, *_rest, lines in calls:
        rows.append(f" -- {call_id} : [{label}] {title}")
        for seq, (sp, text) in enumerate(lines, start=1):
            rows.append(f" ({q(call_id)}, {seq}, '{sp}', {(seq - 1) * 12}, {q(text)}),")
    rows[-1] = rows[-1].rstrip(",")
    out += rows + ["ON CONFLICT (call_id, seq) DO NOTHING;", "",
                   "-- 통화 → 상담사(인사정보) 연결",
                   "UPDATE stt_call s SET agent_emp_id = e.emp_id",
                   "  FROM employee e",
                   " WHERE s.call_id LIKE 'DEMO-%' AND s.agent_emp_id IS NULL AND e.emp_group = '상담사'",
                   "   AND e.emp_name = regexp_replace(s.agent_name, '^상담사\\s*', '');", ""]
    return "\n".join(out)


def build_excels(folder: Path) -> list[Path]:
    from app.services import dialog_excel
    folder.mkdir(parents=True, exist_ok=True)
    paths = []
    for call_id, label, title, *_rest, lines in CALLS + PRE_CALLS:
        wb = load_workbook(BytesIO(dialog_excel.template()))     # 업로드 양식 그대로 (머리글·화자 선택 목록)
        ws = wb.active
        ws.delete_rows(2, ws.max_row)
        for sp, text in lines:
            ws.append([SPEAKER_KO[sp], text])
        sub = folder / ("사전제보" if "PRE" in call_id else "")
        sub.mkdir(parents=True, exist_ok=True)
        path = sub / f"{label.replace(' ', '_')}_{title.replace(' ', '_').replace('/', '_')}.xlsx"
        wb.save(path)
        dialog_excel.parse(path.read_bytes())                    # 업로드 화면과 같은 검사 통과 확인
        paths.append(path)
    return paths


def main() -> None:
    sql_path = ROOT / "sql" / "11_demo_scripts.sql"
    sql_path.write_text(build_sql(), encoding="utf-8")
    print(f"  - {sql_path.relative_to(ROOT)} (통화 {len(CALLS) + len(PRE_CALLS)}건)")
    paths = build_excels(ROOT / "demo" / "stt_excel")
    print(f"  - demo/stt_excel 엑셀 {len(paths)}개 (시연 {len(CALLS)} + 사전제보 {len(PRE_CALLS)})")


if __name__ == "__main__":
    main()
